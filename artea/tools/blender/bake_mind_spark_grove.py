"""Bake one Mind Spark grove zone to a GLB, the way Milo is baked.

Why this exists
---------------
MindSparkWorldOne is generated by GDScript at runtime: ~27,000 MeshInstance3D
nodes, 82% of every mesh in the art gallery scene. Measured, that took the
gallery to 1,161 MB and 104,096 objects against the hub's 348 MB, which is past
what the wasm32 web export can hold alongside a 750 MB pack - so the gallery
came up empty in a browser while working on desktop.

Milo does not have this problem because he is *baked*: Blender builds the
geometry once, offline, and exports a GLB that Godot simply loads. This script
applies the same approach to a grove zone.

The trees are procedurally unique - each trunk is a distinct ArrayMesh - which
is exactly why MultiMesh batching could only recover 19%. Baking sidesteps that
entirely: the uniqueness is resolved once here, at build time, and Godot
receives finished geometry instead of instructions for making it.

Run:
    blender --background --python artea/tools/blender/bake_mind_spark_grove.py

Output:
    assets3D/mind_spark/baked/mind_spark_grove_zone.glb
"""

import math
from pathlib import Path

import bpy


ROOT = Path(__file__).resolve().parents[2]
OUT_DIR = ROOT / "assets3D/mind_spark/baked"
OUT_GLB = OUT_DIR / "mind_spark_grove_zone.glb"

# Mirrors the GDScript grove: 30 trees is Zone 02's authored count, the largest
# single grove in the world.
TREE_COUNT = 30
GROVE_RADIUS = 46.0


def reset_scene():
    bpy.ops.wm.read_factory_settings(use_empty=True)


def material(name, rgb, roughness=0.7, emission=None):
    mat = bpy.data.materials.new(name)
    mat.use_nodes = True
    bsdf = mat.node_tree.nodes.get("Principled BSDF")
    bsdf.inputs["Base Color"].default_value = (*rgb, 1.0)
    bsdf.inputs["Roughness"].default_value = roughness
    if emission is not None and "Emission Color" in bsdf.inputs:
        bsdf.inputs["Emission Color"].default_value = (*emission, 1.0)
        if "Emission Strength" in bsdf.inputs:
            bsdf.inputs["Emission Strength"].default_value = 1.4
    return mat


def build_tree(index, at, scale, bark, foliage, data_glow):
    """One bio-data tree: tapered trunk, canopy, and a data ring."""
    parts = []

    # Trunk. A cone gives the taper in a single primitive rather than the
    # multi-segment curve the runtime version builds, which is where most of
    # its per-tree mesh count came from.
    bpy.ops.mesh.primitive_cone_add(
        vertices=10, radius1=0.62, radius2=0.26, depth=6.2,
        location=(at[0], at[1], 3.1))
    trunk = bpy.context.object
    trunk.name = "GroveTrunk_%02d" % index
    trunk.data.materials.append(bark)
    parts.append(trunk)

    # Canopy: two offset icospheres read as a full crown at gameplay distance
    # and cost 2 meshes instead of dozens of leaf cards.
    for lobe, (dx, dy, dz, r) in enumerate((
            (0.0, 0.0, 7.4, 2.9),
            (0.9, 0.5, 6.4, 2.1))):
        bpy.ops.mesh.primitive_ico_sphere_add(
            subdivisions=2, radius=r, location=(at[0] + dx, at[1] + dy, dz))
        lobe_obj = bpy.context.object
        lobe_obj.name = "GroveCanopy_%02d_%d" % (index, lobe)
        lobe_obj.data.materials.append(foliage)
        parts.append(lobe_obj)

    # The cyan data ring that gives these trees their identity.
    bpy.ops.mesh.primitive_torus_add(
        major_radius=1.15, minor_radius=0.11,
        major_segments=16, minor_segments=6,
        location=(at[0], at[1], 1.6))
    ring = bpy.context.object
    ring.name = "GroveDataRing_%02d" % index
    ring.data.materials.append(data_glow)
    parts.append(ring)

    bpy.ops.object.select_all(action="DESELECT")
    for part in parts:
        part.select_set(True)
    bpy.context.view_layer.objects.active = parts[0]
    bpy.ops.object.join()
    tree = bpy.context.object
    tree.name = "MindSparkGroveTree_%02d" % index
    tree.scale = (scale, scale, scale)
    tree.rotation_euler = (0.0, 0.0, math.atan2(at[0], at[1]) + math.pi)
    return tree


def main():
    reset_scene()

    bark = material("GroveBark", (0.26, 0.19, 0.13), 0.82)
    foliage = material("GroveFoliage", (0.16, 0.42, 0.22), 0.74)
    data_glow = material("GroveDataGlow", (0.20, 0.72, 0.82), 0.30,
                         emission=(0.16, 0.62, 0.74))

    trees = []
    for index in range(TREE_COUNT):
        # Deterministic ring-and-spiral placement, matching the authored
        # "no randomness" policy of the runtime layout.
        angle = (index / float(TREE_COUNT)) * math.tau * 2.0
        radius = GROVE_RADIUS * (0.35 + 0.65 * (index / float(TREE_COUNT)))
        at = (math.sin(angle) * radius, math.cos(angle) * radius)
        scale = 0.72 + ((index * 7) % 11) / 11.0 * 0.9
        trees.append(build_tree(index, at, scale, bark, foliage, data_glow))

    # Join the whole grove into one object. This is the entire point: Godot
    # receives a single mesh with three materials instead of thousands of nodes
    # to build and track.
    bpy.ops.object.select_all(action="DESELECT")
    for tree in trees:
        tree.select_set(True)
    bpy.context.view_layer.objects.active = trees[0]
    bpy.ops.object.join()
    grove = bpy.context.object
    grove.name = "MindSparkGroveZone"

    OUT_DIR.mkdir(parents=True, exist_ok=True)
    bpy.ops.object.select_all(action="DESELECT")
    grove.select_set(True)
    bpy.context.view_layer.objects.active = grove
    bpy.ops.export_scene.gltf(
        filepath=str(OUT_GLB),
        export_format="GLB",
        use_selection=True,
        export_materials="EXPORT",
    )

    mesh = grove.data
    print("BAKE_GROVE trees=%d vertices=%d polygons=%d -> %s"
          % (TREE_COUNT, len(mesh.vertices), len(mesh.polygons), OUT_GLB))


main()
