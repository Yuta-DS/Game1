"""Bake Mind Spark World One's static geometry to GLBs.

Why
---
MindSparkWorldOne is generated by GDScript at runtime: ~27,000 MeshInstance3D
nodes, 82% of every mesh in the art gallery scene. Measured, that took the
gallery to 1,161 MB and 104,096 objects against the hub's 348 MB - past what the
wasm32 web export can hold alongside a 750 MB pack, so the gallery came up empty
in a browser while working correctly on desktop.

Milo does not have this problem because he is baked: Blender builds the geometry
once, offline, and Godot loads a finished GLB. This does the same for the two
patterns that account for nearly all of World One's mesh count:

    ModularFloatingFoundation   ~9,665 meshes across six zones
    MindSparkBioDataTree         5,205 meshes (the hero tree)
    grove trees                  ~5,000 meshes (100 trees x 50)

The runtime builder makes each foundation from radial deck plates subdivided
into eight nested micro-cells apiece, then perimeter armour and crystals - which
is where the count comes from. Baking joins each finished island into one mesh.

Placement stays deterministic, matching the authored no-randomness policy, so
baked output lands where the runtime version put it.

Run:
    blender --background --python artea/tools/blender/bake_mind_spark_world_one.py

Outputs (assets3D/mind_spark/baked/):
    mind_spark_foundation_zone_<n>.glb   one per zone
    mind_spark_hero_tree.glb
    mind_spark_grove_zone.glb
"""

import math
from pathlib import Path

import bpy


ROOT = Path(__file__).resolve().parents[2]
OUT_DIR = ROOT / "assets3D/mind_spark/baked"

# Mirrors ZONES / styles in scripts/mind_spark/mind_spark_world_one.gd so the
# baked islands match the authored layout rather than approximating it.
ZONE_STYLES = [
    {"sectors": 16, "depth": 42.0, "crystals": 6, "inner": 0.25, "radius": 96.0,
     "accent": (0.20, 0.72, 0.82)},
    {"sectors": 18, "depth": 58.0, "crystals": 8, "inner": 0.30, "radius": 120.0,
     "accent": (0.36, 0.62, 0.34)},
    {"sectors": 20, "depth": 52.0, "crystals": 7, "inner": 0.28, "radius": 108.0,
     "accent": (0.55, 0.36, 0.78)},
    {"sectors": 15, "depth": 46.0, "crystals": 5, "inner": 0.22, "radius": 92.0,
     "accent": (0.82, 0.68, 0.28)},
    {"sectors": 24, "depth": 72.0, "crystals": 9, "inner": 0.32, "radius": 140.0,
     "accent": (0.55, 0.36, 0.78)},
    {"sectors": 21, "depth": 62.0, "crystals": 7, "inner": 0.27, "radius": 128.0,
     "accent": (0.82, 0.68, 0.28)},
]

GROVE_TREE_COUNT = 30
GROVE_RADIUS = 46.0


def reset_scene():
    bpy.ops.wm.read_factory_settings(use_empty=True)


def material(name, rgb, roughness=0.7, metallic=0.0, emission=None):
    mat = bpy.data.materials.new(name)
    mat.use_nodes = True
    bsdf = mat.node_tree.nodes.get("Principled BSDF")
    bsdf.inputs["Base Color"].default_value = (*rgb, 1.0)
    bsdf.inputs["Roughness"].default_value = roughness
    bsdf.inputs["Metallic"].default_value = metallic
    if emission is not None and "Emission Color" in bsdf.inputs:
        bsdf.inputs["Emission Color"].default_value = (*emission, 1.0)
        if "Emission Strength" in bsdf.inputs:
            bsdf.inputs["Emission Strength"].default_value = 1.5
    return mat


def join(objects, name):
    """Join a list of objects into one mesh. This is the whole point of baking:
    Godot receives a single mesh instead of thousands of nodes to construct."""
    bpy.ops.object.select_all(action="DESELECT")
    for obj in objects:
        obj.select_set(True)
    bpy.context.view_layer.objects.active = objects[0]
    bpy.ops.object.join()
    result = bpy.context.object
    result.name = name
    return result


def export(obj, filename):
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    path = OUT_DIR / filename
    bpy.ops.object.select_all(action="DESELECT")
    obj.select_set(True)
    bpy.context.view_layer.objects.active = obj
    bpy.ops.export_scene.gltf(
        filepath=str(path), export_format="GLB",
        use_selection=True, export_materials="EXPORT")
    mesh = obj.data
    print("BAKED %-38s verts=%-7d polys=%-7d -> %s"
          % (obj.name, len(mesh.vertices), len(mesh.polygons), path.name))
    return path


def radial_plate(name, angle_from, angle_to, inner, outer, z_bottom, z_top, mat):
    """One deck wedge, built directly as a mesh rather than as eight nested
    cells. The nested cells existed so each could be recoloured individually in
    the editor; baked geometry does not need that, and they were the single
    largest contributor to the runtime mesh count."""
    steps = 4
    verts = []
    for step in range(steps + 1):
        angle = angle_from + (angle_to - angle_from) * step / steps
        cos_a, sin_a = math.cos(angle), math.sin(angle)
        verts.append((cos_a * inner, sin_a * inner, z_bottom))
        verts.append((cos_a * outer, sin_a * outer, z_bottom))
        verts.append((cos_a * inner, sin_a * inner, z_top))
        verts.append((cos_a * outer, sin_a * outer, z_top))
    faces = []
    for step in range(steps):
        base = step * 4
        nxt = base + 4
        faces.append((base + 2, base + 3, nxt + 3, nxt + 2))      # top
        faces.append((base, nxt, nxt + 1, base + 1))              # bottom
        faces.append((base + 1, nxt + 1, nxt + 3, base + 3))      # outer rim
        faces.append((base, base + 2, nxt + 2, nxt))              # inner rim
    mesh = bpy.data.meshes.new(name + "Mesh")
    mesh.from_pydata(verts, [], faces)
    mesh.update()
    obj = bpy.data.objects.new(name, mesh)
    bpy.context.collection.objects.link(obj)
    obj.data.materials.append(mat)
    return obj


def build_foundation(zone_index):
    style = ZONE_STYLES[zone_index]
    radius = style["radius"]
    deck = material("IslandDeck_%d" % zone_index, (0.42, 0.45, 0.50), 0.62, 0.25)
    hull = material("IslandHull_%d" % zone_index, (0.20, 0.22, 0.27), 0.78, 0.15)
    accent = material("IslandAccent_%d" % zone_index, style["accent"], 0.30,
                      emission=style["accent"])
    parts = []

    sector_count = int(style["sectors"])
    step = math.tau / sector_count
    for sector in range(sector_count):
        centre = step * sector + zone_index * 0.07
        gap = step * 0.075
        parts.append(radial_plate(
            "DeckPlate_%02d" % sector,
            centre - step * 0.5 + gap, centre + step * 0.5 - gap,
            radius * style["inner"], radius * 0.945, -0.02, 0.275, deck))

    # The underside hull: one cone standing in for the runtime version's
    # stacked taper rings.
    bpy.ops.mesh.primitive_cone_add(
        vertices=sector_count, radius1=radius * 0.92, radius2=radius * 0.10,
        depth=style["depth"], location=(0, 0, -style["depth"] * 0.5))
    hull_obj = bpy.context.object
    hull_obj.name = "IslandHull"
    hull_obj.data.materials.append(hull)
    parts.append(hull_obj)

    # Accent crystals around the rim.
    for crystal in range(int(style["crystals"])):
        angle = math.tau * crystal / float(style["crystals"])
        bpy.ops.mesh.primitive_cone_add(
            vertices=6, radius1=2.6, radius2=0.0, depth=9.0,
            location=(math.cos(angle) * radius * 0.86,
                      math.sin(angle) * radius * 0.86, 4.5))
        spike = bpy.context.object
        spike.name = "RimCrystal_%02d" % crystal
        spike.data.materials.append(accent)
        parts.append(spike)

    return join(parts, "MindSparkFoundationZone%02d" % (zone_index + 1))


def build_tree(index, at, scale, bark, foliage, glow, hero=False):
    parts = []
    trunk_height = 16.0 if hero else 6.2
    trunk_radius = 1.8 if hero else 0.62
    bpy.ops.mesh.primitive_cone_add(
        vertices=12 if hero else 10, radius1=trunk_radius,
        radius2=trunk_radius * 0.42, depth=trunk_height,
        location=(at[0], at[1], trunk_height * 0.5))
    trunk = bpy.context.object
    trunk.name = "Trunk_%02d" % index
    trunk.data.materials.append(bark)
    parts.append(trunk)

    lobes = ((0.0, 0.0, trunk_height * 1.18, trunk_radius * 4.6),
             (0.9, 0.5, trunk_height * 1.02, trunk_radius * 3.4),
             (-0.8, 0.4, trunk_height * 1.10, trunk_radius * 3.0)) if hero else \
            ((0.0, 0.0, 7.4, 2.9), (0.9, 0.5, 6.4, 2.1))
    for lobe_index, (dx, dy, dz, r) in enumerate(lobes):
        bpy.ops.mesh.primitive_ico_sphere_add(
            subdivisions=3 if hero else 2, radius=r,
            location=(at[0] + dx, at[1] + dy, dz))
        lobe = bpy.context.object
        lobe.name = "Canopy_%02d_%d" % (index, lobe_index)
        lobe.data.materials.append(foliage)
        parts.append(lobe)

    ring_count = 3 if hero else 1
    for ring_index in range(ring_count):
        bpy.ops.mesh.primitive_torus_add(
            major_radius=trunk_radius * 1.9, minor_radius=trunk_radius * 0.18,
            major_segments=20 if hero else 16, minor_segments=6,
            location=(at[0], at[1], 1.6 + ring_index * trunk_height * 0.3))
        ring = bpy.context.object
        ring.name = "DataRing_%02d_%d" % (index, ring_index)
        ring.data.materials.append(glow)
        parts.append(ring)

    tree = join(parts, "Tree_%02d" % index)
    tree.scale = (scale, scale, scale)
    tree.rotation_euler = (0.0, 0.0, math.atan2(at[0], at[1]) + math.pi)
    return tree


def main():
    results = []

    # Six island foundations.
    for zone_index in range(len(ZONE_STYLES)):
        reset_scene()
        foundation = build_foundation(zone_index)
        results.append(export(foundation,
                              "mind_spark_foundation_zone_%02d.glb" % (zone_index + 1)))

    # The hero tree.
    reset_scene()
    bark = material("HeroBark", (0.28, 0.20, 0.14), 0.82)
    foliage = material("HeroFoliage", (0.18, 0.46, 0.24), 0.72)
    glow = material("HeroGlow", (0.20, 0.72, 0.82), 0.28, emission=(0.16, 0.62, 0.74))
    hero = build_tree(0, (0.0, 0.0), 1.0, bark, foliage, glow, hero=True)
    hero.name = "MindSparkHeroTree"
    results.append(export(hero, "mind_spark_hero_tree.glb"))

    # A grove zone.
    reset_scene()
    bark = material("GroveBark", (0.26, 0.19, 0.13), 0.82)
    foliage = material("GroveFoliage", (0.16, 0.42, 0.22), 0.74)
    glow = material("GroveGlow", (0.20, 0.72, 0.82), 0.30, emission=(0.16, 0.62, 0.74))
    trees = []
    for index in range(GROVE_TREE_COUNT):
        angle = (index / float(GROVE_TREE_COUNT)) * math.tau * 2.0
        radius = GROVE_RADIUS * (0.35 + 0.65 * (index / float(GROVE_TREE_COUNT)))
        at = (math.sin(angle) * radius, math.cos(angle) * radius)
        scale = 0.72 + ((index * 7) % 11) / 11.0 * 0.9
        trees.append(build_tree(index, at, scale, bark, foliage, glow))
    grove = join(trees, "MindSparkGroveZone")
    results.append(export(grove, "mind_spark_grove_zone.glb"))

    total = sum(path.stat().st_size for path in results)
    print("BAKE_TOTAL files=%d bytes=%d (%.1f MB)"
          % (len(results), total, total / 1048576.0))


main()
